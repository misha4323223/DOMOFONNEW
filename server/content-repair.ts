/** Опечатки, которые портят только пунктуацию: сюда выносим то, что не слово. */
const PUNCTUATION_FIXES: ReadonlyArray<readonly [RegExp, string]> = [
  [/\s+([,.;:!?])/g, "$1"], // пробел перед знаком препинания
  // Пробел после запятой ставим только перед русским словом: иначе пострадали
  // бы ссылки и телефоны («tel:+7…», «https://…»).
  [/([,;])(?=[а-яёА-ЯЁ])/g, "$1 "],
  [/\.(?=[А-ЯЁ])/g, ". "], // слиплись два предложения
  [/!{2,}/g, "!"],
  [/ {2,}/g, " "],
];

/** Текст по краям не трогаем только здесь: пробел в конце склеивает его со ссылкой. */
function keepsEdgeSpaces(path: string): boolean {
  return path.startsWith("form.");
}

/** Ссылка должна быть ссылкой: оставляем только адрес, текст — выкидываем. */
function fixHref(value: string): string {
  const head = value.trim().split(/\s+/)[0] ?? "";
  return /^(tel:|mailto:|https?:|#|\/)/i.test(head) ? head : "";
}

function fixText(value: string, path: string): string {
  // Имя поля может быть и `href`, и `phoneHref`, и `studioHref`.
  const isHref = /href$/i.test(path);
  let out = isHref ? value : keepsEdgeSpaces(path) ? value : value.trim();

  if (isHref) return fixHref(out);

  const exact = EXACT_FIXES.find(([from]) => from === out);
  if (exact) return exact[1];

  for (const [from, to] of TYPO_FIXES) {
    if (out.includes(from)) out = out.split(from).join(to);
  }
  for (const [pattern, to] of PUNCTUATION_FIXES) {
    out = out.replace(pattern, to);
  }
  // Висячая запятая в конце пункта списка («Биометрия,») — почти всегда след
  // правки текста, а не замысел.
  if (!keepsEdgeSpaces(path)) out = out.replace(/,\s*$/, "");
  return out;
}

/** Пройти по контенту и вернуть исправленную копию вместе со списком правок. */
export function repairSiteContent(raw: unknown): {
  value: unknown;
  changes: string[];
} {
  const changes: string[] = [];

  const walk = (node: unknown, path: string): unknown => {
    if (typeof node === "string") {
      const next = fixText(node, path);
      if (next !== node) {
        changes.push(`${path}: «${node.trim()}» → «${next.trim()}»`);
      }
      return next;
    }
    if (Array.isArray(node)) {
      return node.map((item, index) => walk(item, `${path}[${index}]`));
    }
    if (node && typeof node === "object") {
      const out: Record<string, unknown> = {};
      for (const [key, value] of Object.entries(node as Record<string, unknown>)) {
        out[key] = walk(value, path ? `${path}.${key}` : key);
      }
      return out;
    }
    return node;
  };

  const value = walk(raw, "") as {
    footer?: { contactsLinks?: unknown[] };
  } | null;

  // Ссылки-пустышки в подвале убираем целиком: пункт пропадёт из контактов.
  const links = value?.footer?.contactsLinks;
  if (Array.isArray(links)) {
    const kept = links.filter((item) => {
      const href = (item as { href?: unknown } | null)?.href;
      return !(typeof href === "string" && DROPPED_FOOTER_LINKS.includes(href));
    });
    if (kept.length !== links.length) {
      const removed = links.length - kept.length;
      value!.footer!.contactsLinks = kept;
      changes.push(`footer.contactsLinks: убрано ссылок-пустышек — ${removed}`);
    }
  }

  return { value, changes };
}

/**
 * Один раз поправить сохранённый контент сайта. Вызывается при старте контейнера;
 * повторный запуск ничего не записывает (правок не находится).
 */
export async function repairStoredSiteContent(): Promise<void> {
  try {
    const saved = await storage.getSetting(CONTENT_SETTING_KEY);
    if (!saved?.value) return;

    let parsed: unknown;
    try {
      parsed = JSON.parse(saved.value);
    } catch {
      console.error("[content] Контент сайта в базе повреждён — правку текстов пропускаем");
      return;
    }

    const { value, changes } = repairSiteContent(parsed);
    if (changes.length === 0) return;

    await storage.setSetting(CONTENT_SETTING_KEY, JSON.stringify(value));
    console.log(`[content] Исправлены тексты сайта: правок ${changes.length}`);
    for (const line of changes) console.log(`   ${line}`);
  } catch (err) {
    console.error("[content] Не удалось исправить тексты сайта:", err);
  }
}
