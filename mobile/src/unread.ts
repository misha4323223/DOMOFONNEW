import { api, type ChatUnread } from "./api";

/**
 * Непрочитанные сообщения чата.
 *
 * Источник правды — СЕРВЕР (настройка `chat:last-read`): он хранит createdAt
 * последнего прочитанного сообщения и сам считает, сколько сообщений новее.
 *
 * Почему так, а не локальный «якорь» в телефоне: раньше якорь лежал в
 * AsyncStorage, и счётчик над иконкой чата мог «застрять» — расхождение часов
 * телефона и сервера, потеря данных при переустановке, разные якоря у разных
 * устройств админов. Теперь счётчик считает сервер, а сброс — явный вызов
 * markAllChatRead().
 */

/** Сколько сообщений чата ещё не прочитано (считает сервер). */
export function fetchChatUnread(token: string): Promise<ChatUnread> {
  return api.chatUnread(token);
}

/**
 * Явно пометить ВСЕ сообщения чата прочитанными.
 * Сервер сдвигает якорь прочтения на последнее сообщение — счётчик становится
 * 0 и снова начнёт расти только с сообщений, пришедших после этого вызова.
 */
export function markAllChatRead(token: string): Promise<ChatUnread> {
  return api.markChatRead(token);
}
